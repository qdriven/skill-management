#!/usr/bin/env python3
"""Generate a vhs tape from a JSON spec, render a GIF, and extract check frames.

Spec format:
{
  "output": "docs/demo.gif",
  "cleanup": "rm -rf demo-dir",
  "width": 1700, "height": 680, "font_size": 16,
  "font_family": "Cascadia Mono, Microsoft YaHei",
  "steps": [
    {"label": "help", "command": "uv run tool --help < /dev/null", "wait": 3},
    {"label": "TUI", "command": "uv run tool run", "wait": 15}
  ]
}

Rules baked into the generated tape:
- CursorBlink is enabled, otherwise vhs drops idle time and the GIF plays too fast.
- On Windows only: Git Bash is placed first in PATH so ttyd starts it instead of WSL
  bash, and the user's original PATH is appended so go/node/etc. keep resolving.
  On macOS/Linux the environment is left untouched.
- setup runs hidden (cleanup, UTF-8, clean prompt) and cleanup runs again hidden at the end.
- `Require uv` is emitted only when a step actually invokes uv (or spec sets require_uv),
  so Go/Node CLIs work on machines without uv installed.
"""

from __future__ import annotations

import argparse
import json
import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path


def default_font_family() -> str:
    if platform.system() == "Darwin":
        return "Menlo, PingFang SC"
    if os.name == "nt":
        return "Cascadia Mono, Microsoft YaHei"
    return "DejaVu Sans Mono, Noto Sans CJK SC"


def _which(name: str) -> str | None:
    return shutil.which(name)


def _git_bash_dirs() -> list[str]:
    """Locate Git Bash directories on Windows; never WSL's System32 bash.

    Discovery order: RECORD_GIT_BASH override (bash.exe or its directory),
    the Git install root inferred from `git` on PATH, any non-System32
    bash.exe already on PATH, then common install locations (Program Files,
    Program Files (x86), per-user LOCALAPPDATA, scoop, PortableGit).
    """
    if os.name != "nt":
        return []

    candidates: list[Path] = []

    configured = os.environ.get("RECORD_GIT_BASH")
    if configured:
        path = Path(configured)
        candidates.append(path.parent if path.is_file() else path)

    git = _which("git")
    if git:
        root = Path(git).resolve().parent.parent
        candidates.extend([root / "usr" / "bin", root / "bin"])

    # WSL 的 bash.exe 藏在 System32 和 WindowsApps（应用执行别名）里，都要跳过
    wsl_markers = ("system32", "syswow64", "windowsapps")
    for entry in os.environ.get("PATH", "").split(os.pathsep):
        if entry and not any(marker in entry.lower() for marker in wsl_markers):
            candidates.append(Path(entry))

    localappdata = os.environ.get("LOCALAPPDATA")
    if localappdata:
        candidates.extend(
            [Path(localappdata) / "Programs" / "Git" / "usr" / "bin",
             Path(localappdata) / "Programs" / "Git" / "bin"]
        )
    candidates.extend(
        [
            Path(r"C:\Program Files\Git\usr\bin"),
            Path(r"C:\Program Files\Git\bin"),
            Path(r"C:\Program Files (x86)\Git\usr\bin"),
            Path.home() / "scoop" / "apps" / "git" / "current" / "usr" / "bin",
        ]
    )

    found: list[str] = []
    for directory in candidates:
        if (directory / "bash.exe").is_file() and str(directory) not in found:
            found.append(str(directory))
    return found


def build_env_path() -> str:
    """Windows-only: prepend Git Bash + tool dirs, then keep the user's PATH."""
    dirs: list[str] = []
    for executable in ("ttyd", "ffmpeg", "uv", "vhs"):
        found = _which(executable)
        if found:
            dirs.append(str(Path(found).parent))
    dirs.extend(_git_bash_dirs())
    dirs.extend([r"C:\Windows\System32", r"C:\Windows"])
    dirs.extend(p for p in os.environ.get("PATH", "").split(";") if p)
    seen: set[str] = set()
    unique: list[str] = []
    for directory in dirs:
        key = directory.lower()
        if key not in seen:
            seen.add(key)
            unique.append(directory)
    return ";".join(unique)


def _quote(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"')


def needs_uv(spec: dict) -> bool:
    if spec.get("require_uv") is not None:
        return bool(spec["require_uv"])
    return any("uv" in step.get("command", "") for step in spec.get("steps", []))


def build_tape(spec: dict, output: str) -> str:
    lines = [
        "# Generated by record-terminal-demo",
        f"Output {output}",
        "",
    ]
    if needs_uv(spec):
        lines.append("Require uv")
        lines.append("")
    if os.name == "nt":
        lines.append(f'Env PATH "{_quote(build_env_path())}"')
    lines.extend(
        [
            'Set Shell "bash"',
            f'Set FontFamily "{_quote(spec.get("font_family") or default_font_family())}"',
            f'Set FontSize {spec.get("font_size", 16)}',
            f'Set Width {spec.get("width", 1700)}',
            f'Set Height {spec.get("height", 680)}',
            f'Set Padding {spec.get("padding", 24)}',
            "Set CursorBlink true",
            f'Set TypingSpeed {spec.get("typing_speed", "8ms")}',
            "",
            "Hide",
            "Sleep 2s",
        ]
    )

    cleanup = spec.get("cleanup")
    setup = []
    if cleanup:
        setup.append(cleanup)
    setup.extend(
        [
            "export PYTHONUTF8=1",
            "bind 'set enable-bracketed-paste off'",
            "PS1='$ '",
            "clear",
        ]
    )
    for command in setup:
        lines.extend([f'Type "{_quote(command)}"', "Enter"])
    lines.extend(["Sleep 1s", "Show", ""])

    for index, step in enumerate(spec["steps"], start=1):
        command = step["command"]
        label = step.get("label") or command
        lines.extend(
            [
                f"# {index}. {label}",
                f'Type "{_quote(command)}"',
                "Enter",
                f"Sleep {step.get('wait', 5)}s",
                "",
            ]
        )

    if cleanup:
        lines.extend(["Hide", f'Type "{_quote(cleanup)}"', "Enter", "Sleep 1s", "Show", ""])
    return "\n".join(lines)


def run(command: list[str], *, cwd: Path) -> subprocess.CompletedProcess:
    print("+", " ".join(command), flush=True)
    return subprocess.run(command, cwd=cwd, check=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path, help="JSON spec path")
    parser.add_argument("--cwd", type=Path, default=Path.cwd(), help="working directory for vhs")
    parser.add_argument("--tape", type=Path, help="tape output path (default: next to GIF)")
    parser.add_argument(
        "--verify",
        default="",
        help="comma-separated seconds to extract as PNG frames, e.g. 2,14,29",
    )
    args = parser.parse_args()

    for executable in ("vhs", "ffmpeg", "ttyd"):
        if not _which(executable):
            print(f"error: {executable} not found on PATH", file=sys.stderr)
            return 2

    spec = json.loads(args.spec.read_text(encoding="utf-8"))
    if not spec.get("output") or not spec.get("steps"):
        print("error: spec requires 'output' and non-empty 'steps'", file=sys.stderr)
        return 2

    cwd = args.cwd.resolve()
    output_abs = (cwd / spec["output"]).resolve() if not Path(spec["output"]).is_absolute() else Path(spec["output"])
    output_rel = Path(os.path.relpath(output_abs, cwd)).as_posix()
    output_abs.parent.mkdir(parents=True, exist_ok=True)

    tape_path = args.tape or output_abs.with_suffix(".tape")
    tape_path = (cwd / tape_path).resolve() if not tape_path.is_absolute() else tape_path
    tape_path.parent.mkdir(parents=True, exist_ok=True)
    tape_path.write_text(build_tape(spec, output_rel), encoding="utf-8")
    print(f"tape: {tape_path}")

    run([_which("vhs") or "vhs", str(tape_path), "-o", output_rel], cwd=cwd)

    ffprobe = _which("ffprobe")
    if ffprobe:
        probe = subprocess.run(
            [ffprobe, "-v", "error", "-show_entries", "format=duration",
             "-of", "default=noprint_wrappers=1", str(output_abs)],
            capture_output=True, text=True, check=False,
        )
        print(probe.stdout.strip() or f"size: {output_abs.stat().st_size} bytes")

    times = [value.strip() for value in args.verify.split(",") if value.strip()]
    if times:
        frame_dir = output_abs.parent / "frames"
        frame_dir.mkdir(exist_ok=True)
        ffmpeg = _which("ffmpeg") or "ffmpeg"
        for timestamp in times:
            frame = frame_dir / f"t{timestamp}.png"
            subprocess.run(
                [ffmpeg, "-v", "error", "-ss", timestamp, "-i", str(output_abs),
                 "-frames:v", "1", str(frame)],
                check=False,
            )
            print(f"frame: {frame}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
